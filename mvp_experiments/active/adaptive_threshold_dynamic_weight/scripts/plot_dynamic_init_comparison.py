#!/usr/bin/env python3
"""Compare scalar and random initializations for DynamicThreshold GWNet.

The script only reads post-hoc analysis CSV/JSON files generated by
``analyze_dynamic_threshold_time_evolution.py``. It does not import BasicTS or
touch model checkpoints.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[4]


RESULT_ROOT = _repo_root() / "mvp_experiments/active/adaptive_threshold_dynamic_weight/results"
OUT_DIR = RESULT_ROOT / "init_compare_gspK64_noaddapt_20260530"
META_PATH = _repo_root() / "BasicTS/datasets/SD/meta.csv"

RUNS = {
    "scalar": {
        "label": "scalar init",
        "color": "#2563eb",
        "path": RESULT_ROOT / "init_compare_scalar_gspK64_noaddapt_20260530",
    },
    "rand16_48": {
        "label": "random degree 16-48",
        "color": "#f97316",
        "path": RESULT_ROOT / "init_compare_rand16_48_gspK64_noaddapt_20260530",
    },
    "rand8_64": {
        "label": "random degree 8-64",
        "color": "#16a34a",
        "path": RESULT_ROOT / "init_compare_rand8_64_gspK64_noaddapt_20260530",
    },
}


def _load_run(run_key: str, cfg: dict[str, object]) -> dict[str, object]:
    path = Path(cfg["path"])
    if not path.exists():
        raise FileNotFoundError(f"Missing analysis directory: {path}")
    node = pd.read_csv(path / "node_dynamic_threshold_summary.csv")
    tod = pd.read_csv(path / "time_of_day_summary.csv")
    sample = pd.read_csv(path / "sample_time_series.csv")
    summary = json.loads((path / "analysis_summary.json").read_text(encoding="utf-8"))
    return {
        "key": run_key,
        "label": str(cfg["label"]),
        "color": str(cfg["color"]),
        "node": node,
        "tod": tod,
        "sample": sample,
        "summary": summary,
    }


def _moving_average(values: np.ndarray, window: int) -> np.ndarray:
    if window <= 1 or values.size <= window:
        return values
    kernel = np.ones(window, dtype=float) / window
    return np.convolve(values, kernel, mode="same")


def _style() -> None:
    matplotlib.rcParams.update(
        {
            "font.size": 10,
            "font.family": "serif",
            "font.serif": ["Times New Roman", "Times", "DejaVu Serif"],
            "axes.labelsize": 10,
            "axes.titlesize": 11,
            "xtick.labelsize": 9,
            "ytick.labelsize": 9,
            "legend.fontsize": 9,
            "figure.dpi": 150,
            "savefig.dpi": 300,
            "savefig.bbox": "tight",
            "savefig.pad_inches": 0.05,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "axes.grid": True,
            "grid.alpha": 0.22,
            "grid.linewidth": 0.6,
        }
    )


def _save(fig: plt.Figure, name: str) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT_DIR / f"{name}.png")
    fig.savefig(OUT_DIR / f"{name}.pdf")
    plt.close(fig)


def _summary_rows(runs: list[dict[str, object]]) -> pd.DataFrame:
    rows = []
    for run in runs:
        node = run["node"]
        tod = run["tod"]
        assert isinstance(node, pd.DataFrame)
        assert isinstance(tod, pd.DataFrame)
        degree = node["active_out_degree_mean"].to_numpy(dtype=float)
        radius = node["radius_m_mean"].to_numpy(dtype=float)
        rows.append(
            {
                "init": run["label"],
                "mean_degree": float(np.mean(degree)),
                "median_degree": float(np.median(degree)),
                "p75_degree": float(np.percentile(degree, 75)),
                "p90_degree": float(np.percentile(degree, 90)),
                "nodes_degree_ge_63_5": int(np.sum(degree >= 63.5)),
                "nodes_degree_ge_60": int(np.sum(degree >= 60.0)),
                "mean_radius_m": float(np.mean(radius)),
                "median_radius_m": float(np.median(radius)),
                "radius_iqr_m": float(np.percentile(radius, 75) - np.percentile(radius, 25)),
                "tod_degree_range": float(tod["active_avg_out_degree"].max() - tod["active_avg_out_degree"].min()),
                "tod_radius_range_m": float(tod["radius_m_mean"].max() - tod["radius_m_mean"].min()),
            }
        )
    return pd.DataFrame(rows)


def _plot_distributions(runs: list[dict[str, object]]) -> None:
    fig, axes = plt.subplots(2, 2, figsize=(10.5, 7.2))
    degree_bins = np.linspace(0, 64, 33)
    radius_max = max(float(run["node"]["radius_m_mean"].max()) for run in runs)  # type: ignore[index]
    radius_bins = np.linspace(0, radius_max, 36)

    for run in runs:
        node = run["node"]
        label = str(run["label"])
        color = str(run["color"])
        assert isinstance(node, pd.DataFrame)
        degree = node["active_out_degree_mean"].to_numpy(dtype=float)
        radius = node["radius_m_mean"].to_numpy(dtype=float)

        axes[0, 0].hist(degree, bins=degree_bins, alpha=0.28, color=color, label=label)
        axes[0, 0].hist(degree, bins=degree_bins, histtype="step", linewidth=1.6, color=color)

        axes[0, 1].hist(radius / 1000.0, bins=radius_bins / 1000.0, alpha=0.26, color=color, label=label)
        axes[0, 1].hist(radius / 1000.0, bins=radius_bins / 1000.0, histtype="step", linewidth=1.6, color=color)

        sorted_degree = np.sort(degree)
        q = np.linspace(0, 100, sorted_degree.size)
        axes[1, 0].plot(q, sorted_degree, color=color, linewidth=1.8, label=label)

        sorted_radius = np.sort(radius) / 1000.0
        axes[1, 1].plot(q, sorted_radius, color=color, linewidth=1.8, label=label)

    axes[0, 0].axvline(64, color="#111827", linestyle="--", linewidth=1.0, alpha=0.7)
    axes[0, 0].set_xlabel("Mean active out-degree")
    axes[0, 0].set_ylabel("Node count")
    axes[0, 0].set_title("Degree distribution")
    axes[0, 0].legend(frameon=False)

    axes[0, 1].set_xlabel("Mean radius threshold (km)")
    axes[0, 1].set_ylabel("Node count")
    axes[0, 1].set_title("Radius distribution")

    axes[1, 0].axhline(64, color="#111827", linestyle="--", linewidth=1.0, alpha=0.7)
    axes[1, 0].set_xlabel("Node percentile")
    axes[1, 0].set_ylabel("Mean active out-degree")
    axes[1, 0].set_title("Sorted node degree")

    axes[1, 1].set_xlabel("Node percentile")
    axes[1, 1].set_ylabel("Mean radius threshold (km)")
    axes[1, 1].set_title("Sorted node radius")

    fig.suptitle("Dynamic threshold initialization comparison: GSP K64, no addaptadj", y=1.02)
    fig.tight_layout()
    _save(fig, "init_degree_radius_distributions")


def _plot_time_of_day(runs: list[dict[str, object]]) -> None:
    fig, axes = plt.subplots(2, 1, figsize=(8.6, 6.0), sharex=True)
    for run in runs:
        tod = run["tod"]
        assert isinstance(tod, pd.DataFrame)
        axes[0].plot(
            tod["time_of_day_hour"],
            tod["active_avg_out_degree"],
            color=str(run["color"]),
            linewidth=1.9,
            label=str(run["label"]),
        )
        axes[1].plot(
            tod["time_of_day_hour"],
            tod["radius_m_mean"] / 1000.0,
            color=str(run["color"]),
            linewidth=1.9,
            label=str(run["label"]),
        )

    axes[0].axhline(64, color="#111827", linestyle="--", linewidth=1.0, alpha=0.7)
    axes[0].set_ylabel("Avg active out-degree")
    axes[0].set_title("Time-of-day active degree")
    axes[0].legend(frameon=False, ncol=3, loc="upper right")

    axes[1].set_xlabel("Hour of day")
    axes[1].set_ylabel("Mean radius threshold (km)")
    axes[1].set_title("Time-of-day radius")
    axes[1].set_xlim(0, 24)
    fig.tight_layout()
    _save(fig, "init_time_of_day_curves")


def _plot_node_scatter(runs: list[dict[str, object]]) -> None:
    fig, ax = plt.subplots(figsize=(7.2, 5.2))
    for run in runs:
        node = run["node"]
        assert isinstance(node, pd.DataFrame)
        ax.scatter(
            node["radius_m_mean"] / 1000.0,
            node["active_out_degree_mean"],
            s=14,
            alpha=0.48,
            color=str(run["color"]),
            label=str(run["label"]),
            edgecolors="none",
        )
    ax.axhline(64, color="#111827", linestyle="--", linewidth=1.0, alpha=0.7)
    ax.set_xlabel("Mean radius threshold (km)")
    ax.set_ylabel("Mean active out-degree")
    ax.set_title("Node-wise radius vs active degree")
    ax.legend(frameon=False)
    fig.tight_layout()
    _save(fig, "init_node_radius_vs_degree")


def _plot_sample_series(runs: list[dict[str, object]]) -> None:
    fig, axes = plt.subplots(2, 1, figsize=(10.2, 5.8), sharex=True)
    for run in runs:
        sample = run["sample"]
        assert isinstance(sample, pd.DataFrame)
        x = sample["sample_index"].to_numpy(dtype=float)
        degree = _moving_average(sample["active_avg_out_degree"].to_numpy(dtype=float), 96)
        radius = _moving_average(sample["radius_m_mean"].to_numpy(dtype=float) / 1000.0, 96)
        axes[0].plot(x, degree, color=str(run["color"]), linewidth=1.2, label=str(run["label"]))
        axes[1].plot(x, radius, color=str(run["color"]), linewidth=1.2, label=str(run["label"]))

    axes[0].axhline(64, color="#111827", linestyle="--", linewidth=1.0, alpha=0.7)
    axes[0].set_ylabel("Smoothed avg degree")
    axes[0].set_title("Test-sample trajectory")
    axes[0].legend(frameon=False, ncol=3, loc="upper right")

    axes[1].set_xlabel("Test sample index")
    axes[1].set_ylabel("Smoothed radius (km)")
    fig.tight_layout()
    _save(fig, "init_sample_trajectory")


def _plot_saturation_bars(summary: pd.DataFrame) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(9.0, 3.5))
    colors = [RUNS["scalar"]["color"], RUNS["rand16_48"]["color"], RUNS["rand8_64"]["color"]]
    labels = summary["init"].to_list()
    x = np.arange(len(labels))

    axes[0].bar(x, summary["nodes_degree_ge_63_5"], color=colors, alpha=0.82)
    axes[0].set_xticks(x)
    axes[0].set_xticklabels(labels, rotation=15, ha="right")
    axes[0].set_ylabel("Node count")
    axes[0].set_title("Nodes with degree >= 63.5")

    axes[1].bar(x, summary["mean_degree"], color=colors, alpha=0.82, label="mean")
    axes[1].scatter(x, summary["median_degree"], color="#111827", s=28, zorder=3, label="median")
    axes[1].axhline(64, color="#111827", linestyle="--", linewidth=1.0, alpha=0.7)
    axes[1].set_xticks(x)
    axes[1].set_xticklabels(labels, rotation=15, ha="right")
    axes[1].set_ylabel("Active out-degree")
    axes[1].set_title("Mean and median degree")
    axes[1].legend(frameon=False)

    fig.tight_layout()
    _save(fig, "init_degree_saturation_summary")


def _plot_spatial_degree_delta(runs: list[dict[str, object]]) -> None:
    if not META_PATH.exists():
        return

    by_key = {str(run["key"]): run for run in runs}
    scalar = by_key["scalar"]["node"]
    assert isinstance(scalar, pd.DataFrame)
    meta = pd.read_csv(META_PATH)
    lon_col = "Lng" if "Lng" in meta.columns else "lon"
    lat_col = "Lat" if "Lat" in meta.columns else "lat"
    if lon_col not in meta.columns or lat_col not in meta.columns:
        return

    fig, axes = plt.subplots(1, 2, figsize=(10.5, 5.0), sharex=True, sharey=True, constrained_layout=True)
    comparisons = [
        ("rand16_48", "random degree 16-48 - scalar"),
        ("rand8_64", "random degree 8-64 - scalar"),
    ]
    vmax = 0.0
    deltas = {}
    for key, _title in comparisons:
        node = by_key[key]["node"]
        assert isinstance(node, pd.DataFrame)
        merged = scalar[["node_index", "active_out_degree_mean"]].merge(
            node[["node_index", "active_out_degree_mean"]],
            on="node_index",
            suffixes=("_scalar", "_random"),
        )
        delta = merged["active_out_degree_mean_random"] - merged["active_out_degree_mean_scalar"]
        deltas[key] = delta.to_numpy(dtype=float)
        vmax = max(vmax, float(np.nanmax(np.abs(deltas[key]))))

    vmax = max(vmax, 1.0)
    for ax, (key, title) in zip(axes, comparisons):
        sc = ax.scatter(
            meta[lon_col],
            meta[lat_col],
            c=deltas[key],
            cmap="RdYlGn",
            vmin=-vmax,
            vmax=vmax,
            s=18,
            alpha=0.86,
            linewidths=0,
        )
        ax.set_title(title)
        ax.set_xlabel("Longitude")
        ax.set_aspect("equal", adjustable="box")
    axes[0].set_ylabel("Latitude")
    cbar = fig.colorbar(sc, ax=axes, orientation="horizontal", fraction=0.08, pad=0.09)
    cbar.set_label("Delta active out-degree")
    fig.suptitle("Spatial pattern of random-init degree change", y=1.04)
    _save(fig, "init_spatial_degree_delta_vs_scalar")


def main() -> None:
    _style()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    runs = [_load_run(key, cfg) for key, cfg in RUNS.items()]
    summary = _summary_rows(runs)
    summary.to_csv(OUT_DIR / "init_comparison_summary.csv", index=False)
    (OUT_DIR / "init_comparison_summary.json").write_text(
        json.dumps(summary.to_dict(orient="records"), indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    _plot_distributions(runs)
    _plot_time_of_day(runs)
    _plot_node_scatter(runs)
    _plot_sample_series(runs)
    _plot_saturation_bars(summary)
    _plot_spatial_degree_delta(runs)
    print(json.dumps({"output_dir": str(OUT_DIR), "summary": summary.to_dict(orient="records")}, indent=2))


if __name__ == "__main__":
    main()
